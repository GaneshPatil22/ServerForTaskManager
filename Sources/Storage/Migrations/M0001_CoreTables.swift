import Logging
import PostgresMigrations
import PostgresNIO

/// The domain tables from `Brain/docs/01-domain.md`.
///
/// Three rules are enforced by the database itself, not only by Swift code:
///
/// 1. **Every primary key is `(user_id, id)`, and every reference includes
///    `user_id`.** A row cannot point at another user's row; the foreign key
///    has nothing to match.
/// 2. **Captures are never deleted and never edited** (domain invariant 2).
///    A trigger allows only `status` to change. Corrections are append-only too.
/// 3. **`confirmed` requires `source = 'user'`** (domain invariant 3).
///
/// The allowed values in every CHECK are written out literally, so this
/// migration never changes after it ships. `SchemaDriftTests` fails if Brain's
/// enums and these lists diverge; the fix is a new migration, not an edit here.
///
/// RLS is enabled with no policies (ADR-0007). On Supabase that denies the
/// auto-generated data API (`anon`, `authenticated`) all access to these
/// tables. It does **not** restrict the server, which connects as the owner;
/// the server's boundary is `UserStore`.
struct M0001_CoreTables: DatabaseMigration {
    static let tiers = ["t0", "t1", "t2", "t3", "user"]
    static let captureSources = ["text", "voice", "image", "share"]
    static let captureStatuses = ["raw", "enriching", "enriched", "failed"]
    static let itemTypes = ["task", "idea", "note", "reminder", "link"]
    static let itemStatuses = ["open", "done", "dropped"]
    static let effortBuckets = ["tiny", "small", "medium", "large", "xlarge", "unknown"]
    static let taskCategories = [
        "paperwork", "errands", "communication", "planning", "deepWork",
        "chores", "money", "learning", "health",
    ]
    static let goalStatuses = ["active", "achieved", "abandoned"]
    static let edgeKinds = ["blocks", "relates", "duplicate", "serves"]
    static let edgeSources = ["t0Rule", "t1Model", "t2Model", "user"]

    static let tables = ["corrections", "edges", "items", "goals", "captures", "users"]

    func apply(connection: PostgresConnection, logger: Logger) async throws {
        for statement in Self.statements {
            try await connection.query(PostgresQuery(unsafeSQL: statement), logger: logger)
        }
    }

    func revert(connection: PostgresConnection, logger: Logger) async throws {
        for table in Self.tables {
            try await connection.query(
                PostgresQuery(unsafeSQL: "DROP TABLE IF EXISTS \(table)"), logger: logger)
        }
        for statement in [
            "DROP FUNCTION IF EXISTS captures_guard()",
            "DROP FUNCTION IF EXISTS append_only_guard()",
            "DROP DOMAIN IF EXISTS ulid",
        ] {
            try await connection.query(PostgresQuery(unsafeSQL: statement), logger: logger)
        }
    }

    /// `IN ('a', 'b')` from a fixed list. Values are compile-time constants
    /// above, never user input.
    static func list(_ values: [String]) -> String {
        "(" + values.map { "'\($0)'" }.joined(separator: ", ") + ")"
    }

    /// A `Classified<T>` field: value, confidence, tier, and the evidence span.
    static func classified(_ name: String, _ sqlType: String, allowed: [String]? = nil)
        -> String
    {
        let valueCheck = allowed.map { " CHECK (\(name) IN \(list($0)))" } ?? ""
        return """
            \(name) \(sqlType)\(valueCheck),
            \(name)_confidence double precision NOT NULL
                CHECK (\(name)_confidence BETWEEN 0 AND 1),
            \(name)_tier text NOT NULL CHECK (\(name)_tier IN \(list(tiers))),
            \(name)_evidence_start bigint,
            \(name)_evidence_end bigint,
            CHECK ((\(name)_evidence_start IS NULL) = (\(name)_evidence_end IS NULL)),
            CHECK (\(name)_evidence_start IS NULL OR
                   (0 <= \(name)_evidence_start AND \(name)_evidence_start <= \(name)_evidence_end))
            """
    }

    static var statements: [String] {
        [
            // Crockford base32, as generated by BrainCore.ULID.
            "CREATE DOMAIN ulid AS text CHECK (VALUE ~ '^[0-9A-HJKMNP-TV-Z]{26}$')",

            """
            CREATE TABLE users (
                id uuid PRIMARY KEY,
                timezone text NOT NULL DEFAULT 'Asia/Kolkata',
                created_at timestamptz NOT NULL DEFAULT now()
            )
            """,

            """
            CREATE TABLE captures (
                user_id uuid NOT NULL REFERENCES users (id),
                id ulid NOT NULL,
                raw_text text NOT NULL,
                source text NOT NULL CHECK (source IN \(list(captureSources))),
                status text NOT NULL CHECK (status IN \(list(captureStatuses))),
                idempotency_key text,
                created_at timestamptz NOT NULL,
                PRIMARY KEY (user_id, id)
            )
            """,
            """
            CREATE UNIQUE INDEX captures_idempotency_key
                ON captures (user_id, idempotency_key) WHERE idempotency_key IS NOT NULL
            """,
            """
            CREATE FUNCTION captures_guard() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
                IF TG_OP = 'DELETE' THEN
                    RAISE EXCEPTION 'captures are never deleted (domain invariant 2)';
                END IF;
                IF NEW.user_id <> OLD.user_id OR NEW.id <> OLD.id
                   OR NEW.raw_text <> OLD.raw_text OR NEW.source <> OLD.source
                   OR NEW.created_at <> OLD.created_at
                   OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key THEN
                    RAISE EXCEPTION 'captures are append-only: only status may change';
                END IF;
                RETURN NEW;
            END
            $$
            """,
            """
            CREATE TRIGGER captures_guard BEFORE UPDATE OR DELETE ON captures
                FOR EACH ROW EXECUTE FUNCTION captures_guard()
            """,

            """
            CREATE TABLE goals (
                user_id uuid NOT NULL REFERENCES users (id),
                id ulid NOT NULL,
                title text NOT NULL,
                status text NOT NULL CHECK (status IN \(list(goalStatuses))),
                created_at timestamptz NOT NULL,
                PRIMARY KEY (user_id, id)
            )
            """,

            """
            CREATE TABLE items (
                user_id uuid NOT NULL REFERENCES users (id),
                id ulid NOT NULL,
                capture_id ulid,
                title text NOT NULL,
                status text NOT NULL CHECK (status IN \(list(itemStatuses))),
                \(classified("type", "text", allowed: itemTypes)),
                \(classified("effort", "text", allowed: effortBuckets)),
                \(classified("due_at", "timestamptz")),
                \(classified("goal_id", "ulid")),
                \(classified("category", "text", allowed: taskCategories)),
                created_at timestamptz NOT NULL,
                updated_at timestamptz NOT NULL,
                PRIMARY KEY (user_id, id),
                FOREIGN KEY (user_id, capture_id) REFERENCES captures (user_id, id),
                FOREIGN KEY (user_id, goal_id) REFERENCES goals (user_id, id)
            )
            """,

            // `serves` points at a goal; every other kind points at an item.
            """
            CREATE TABLE edges (
                user_id uuid NOT NULL REFERENCES users (id),
                id ulid NOT NULL,
                from_item_id ulid NOT NULL,
                to_item_id ulid,
                to_goal_id ulid,
                kind text NOT NULL CHECK (kind IN \(list(edgeKinds))),
                confidence double precision NOT NULL CHECK (confidence BETWEEN 0 AND 1),
                source text NOT NULL CHECK (source IN \(list(edgeSources))),
                confirmed boolean NOT NULL DEFAULT false,
                created_at timestamptz NOT NULL DEFAULT now(),
                PRIMARY KEY (user_id, id),
                FOREIGN KEY (user_id, from_item_id) REFERENCES items (user_id, id),
                FOREIGN KEY (user_id, to_item_id) REFERENCES items (user_id, id),
                FOREIGN KEY (user_id, to_goal_id) REFERENCES goals (user_id, id),
                CHECK ((to_item_id IS NULL) <> (to_goal_id IS NULL)),
                CHECK ((kind = 'serves') = (to_goal_id IS NOT NULL)),
                CHECK (to_item_id IS NULL OR to_item_id <> from_item_id),
                CHECK (NOT confirmed OR source = 'user')
            )
            """,
            """
            CREATE UNIQUE INDEX edges_unique_item_target
                ON edges (user_id, from_item_id, to_item_id, kind) WHERE to_item_id IS NOT NULL
            """,
            """
            CREATE UNIQUE INDEX edges_unique_goal_target
                ON edges (user_id, from_item_id, to_goal_id, kind) WHERE to_goal_id IS NOT NULL
            """,

            """
            CREATE TABLE corrections (
                user_id uuid NOT NULL REFERENCES users (id),
                id ulid NOT NULL,
                target_id ulid NOT NULL,
                field text NOT NULL,
                before_value text,
                after_value text,
                tier text NOT NULL CHECK (tier IN \(list(tiers))),
                created_at timestamptz NOT NULL,
                PRIMARY KEY (user_id, id)
            )
            """,
            """
            CREATE FUNCTION append_only_guard() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
                RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
            END
            $$
            """,
            """
            CREATE TRIGGER corrections_append_only BEFORE UPDATE OR DELETE ON corrections
                FOR EACH ROW EXECUTE FUNCTION append_only_guard()
            """,
        ]
            + tables.map { "ALTER TABLE \($0) ENABLE ROW LEVEL SECURITY" }
    }
}
